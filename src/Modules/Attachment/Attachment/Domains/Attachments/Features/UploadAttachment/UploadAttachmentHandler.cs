using Shared.Core.MultiTenancy;
using Attachment.Contracts.Attachments.Commands;
using Attachment.Domains.Attachments.Exceptions;
using Attachment.Infrastructure.Authorization;
using Attachment.Infrastructure.BackgroundJobs;
using Attachment.Infrastructure.Configuration;
using Attachment.Infrastructure.Storage;
using Attachment.Infrastructure.Validation;
using Attachment.Resources;
using Microsoft.Extensions.Localization;
using Microsoft.Extensions.Options;

namespace Attachment.Domains.Attachments.Features.UploadAttachment;

public class UploadAttachmentCommandValidator : AbstractValidator<UploadAttachmentCommand>
{
    public UploadAttachmentCommandValidator(IStringLocalizer<AttachmentResource> localizer)
    {
        RuleFor(x => x.FileName)
            .NotEmpty().WithMessage(_ => localizer["Validation.FileName.Required"])
            .MaximumLength(500).WithMessage(_ => localizer["Validation.FileName.MaxLength"]);

        RuleFor(x => x.ContentType)
            .NotEmpty().WithMessage(_ => localizer["Validation.ContentType.Required"]);

        RuleFor(x => x.FileSize)
            .GreaterThan(0).WithMessage(_ => localizer["Validation.FileSize.Min"]);

        RuleFor(x => x.FileStream)
            .NotNull().WithMessage(_ => localizer["Validation.FileStream.Required"]);

        RuleFor(x => x.EntityId)
            .NotEmpty().When(x => x.EntityType.HasValue)
            .WithMessage(_ => localizer["Validation.EntityId.Required"]);
    }
}

/// <summary>
/// Validates (server-determined type), authorizes (entity policy when requested) and stores a file in two
/// phases, so the database always knows about every blob:
/// <list type="number">
/// <item>Insert the row as <c>Uploading</c> (invisible to every read) and commit.</item>
/// <item>Write the blob, then mark the row <c>Ready</c> with the real size and SHA-256 and commit
/// (raises <c>AttachmentUploadedEvent</c>).</item>
/// </list>
/// If phase 2 fails, the blob is deleted and the row removed right away (best effort); whatever that cannot clean
/// up stays <c>Uploading</c> and is removed by the reconciliation sweeper. Thumbnails are generated by
/// <see cref="GenerateThumbnailJob"/> after the upload, not in the request.
/// </summary>
public class UploadAttachmentHandler(
    IAttachmentRepository repository,
    IStorageService storageService,
    IFileValidationService fileValidationService,
    IAttachmentAccessService accessService,
    IAttachmentUrls urls,
    IAttachmentBackgroundJobs backgroundJobs,
    IOptions<AttachmentOptions> options,
    TimeProvider time,
    ITenantContext tenantContext,
    ILogger<UploadAttachmentHandler> logger)
    : ICommandHandler<UploadAttachmentCommand, UploadAttachmentResult>
{
    public async Task<UploadAttachmentResult> Handle(
        UploadAttachmentCommand command,
        CancellationToken cancellationToken)
    {
        var uploadedBy = command.UploadedBy
            ?? accessService.Current.UserId
            ?? throw new UnauthorizedException("User must be authenticated to upload files.");

        if (command.EnforceEntityAccessPolicy && command.EntityType is { } entityType)
        {
            await accessService.EnsureCanAttachToEntityAsync(
                entityType, command.EntityId ?? Guid.Empty, cancellationToken);
        }

        await using var upload = await SeekableUpload.CreateAsync(command.FileStream, cancellationToken);

        var validation = await fileValidationService.ValidateFileAsync(
            upload.Stream, command.FileName, command.ContentType, command.FileSize, command.Type, cancellationToken);

        if (!validation.IsValid || validation.Detected is not { } detected)
            throw new InvalidFileException($"File validation failed: {string.Join(", ", validation.Errors)}");

        var contentHash = await ContentHasher.Sha256HexAsync(upload.Stream, cancellationToken);
        var length = upload.Stream.Length; // known upload length: no metadata round trip needed

        var id = Guid.NewGuid();
        var storagePath = StoragePaths.ForUpload(
            tenantContext.TenantId ?? throw new TenantNotResolvedException("upload"), id, detected.Extension, time.GetUtcNow().UtcDateTime);

        // Phase 1: the row exists (Uploading) before a single byte is stored. Nothing to clean up if this fails.
        var attachment = AttachmentFile.StartUpload(
            id,
            $"{id:N}{detected.Extension}",
            validation.SafeFileName,
            detected.ContentType,
            length,
            storagePath,
            urls.File(id),
            detected.Type,
            uploadedBy,
            command.EntityType,
            command.EntityId,
            command.Description,
            command.IsPublic);

        await repository.AddAsync(attachment, cancellationToken);
        await repository.SaveChangesAsync(cancellationToken);

        // Phase 2: blob, then Ready.
        try
        {
            upload.Stream.Position = 0;
            var stored = await storageService.UploadToPathAsync(
                upload.Stream, storagePath, detected.ContentType, cancellationToken);

            attachment.MarkReady(stored.FileSize, contentHash, detected.Width, detected.Height);
            await repository.SaveChangesAsync(cancellationToken);
        }
        catch (Exception ex)
        {
            await AbandonAsync(attachment, ex);
            throw;
        }

        var thumbnailQueued = command.GenerateThumbnail
                              && detected.Type == AttachmentType.Image
                              && options.Value.Image.EnableThumbnailGeneration;
        if (thumbnailQueued)
            backgroundJobs.EnqueueThumbnail(id);

        logger.LogInformation(
            "Attachment {AttachmentId} uploaded by {UserId} ({ContentType}, {Size} bytes)",
            id, uploadedBy, detected.ContentType, attachment.FileSize);

        return new UploadAttachmentResult(
            attachment.Id,
            attachment.FileName,
            urls.File(attachment.Id),
            ThumbnailUrl: null, // generated in the background; read it from the attachment later
            attachment.FileSize,
            attachment.ContentType,
            ThumbnailPending: thumbnailQueued);
    }

    /// <summary>
    /// Phase 2 failed: delete the (possibly partial) blob, then the row. Each step is best effort; a row that is
    /// left behind is still <c>Uploading</c> and the sweeper finishes the job.
    /// </summary>
    private async Task AbandonAsync(AttachmentFile attachment, Exception cause)
    {
        logger.LogWarning(cause, "Upload of attachment {AttachmentId} failed; cleaning up", attachment.Id);

        try
        {
            var blobs = await storageService.DeleteBatchAsync([attachment.StoragePath], CancellationToken.None);
            if (!blobs.AllSucceeded)
            {
                logger.LogError("Blob {Path} of failed upload {AttachmentId} could not be deleted; the sweeper retries",
                    attachment.StoragePath, attachment.Id);
                return;
            }

            repository.Delete(attachment);
            await repository.SaveChangesAsync(CancellationToken.None);
        }
        catch (Exception cleanupError)
        {
            logger.LogWarning(cleanupError,
                "Row of failed upload {AttachmentId} could not be removed; the sweeper removes it", attachment.Id);
        }
    }
}
